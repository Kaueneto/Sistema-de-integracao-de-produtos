CREATE OR REPLACE FUNCTION atualizar_data_produto() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.atualizado_em := GREATEST(clock_timestamp(), OLD.atualizado_em + INTERVAL '1 microsecond');
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_produtos_atualizado_em ON produtos;
CREATE TRIGGER trg_produtos_atualizado_em BEFORE UPDATE ON produtos
FOR EACH ROW EXECUTE FUNCTION atualizar_data_produto();

CREATE OR REPLACE VIEW public.vw_integracao_produtos AS
SELECT id_produto, nome, descricao, categoria, preco, unidade_medida, ativo, atualizado_em
FROM produtos;

