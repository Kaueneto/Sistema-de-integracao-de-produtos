CREATE TABLE IF NOT EXISTS categorias (
  nome VARCHAR(100) PRIMARY KEY CHECK (btrim(nome) <> ''),
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS marcas (
  nome VARCHAR(100) PRIMARY KEY CHECK (btrim(nome) <> ''),
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS fornecedores (
  nome VARCHAR(120) PRIMARY KEY CHECK (btrim(nome) <> ''),
  contato VARCHAR(254),
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS unidades_medida (
  sigla VARCHAR(20) PRIMARY KEY CHECK (btrim(sigla) <> ''),
  descricao VARCHAR(100) NOT NULL DEFAULT '',
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS produtos (
  id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_produto > 0),
  nome VARCHAR(120) NOT NULL CHECK (btrim(nome) <> ''),
  descricao VARCHAR(500) NOT NULL DEFAULT '',
  categoria VARCHAR(100) NOT NULL CHECK (btrim(categoria) <> ''),
  marca VARCHAR(100),
  fornecedor VARCHAR(120),
  preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
  unidade_medida VARCHAR(20) NOT NULL CHECK (btrim(unidade_medida) <> ''),
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

